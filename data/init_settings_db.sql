-- 3. Stored Procedure: Get App Settings
CREATE OR REPLACE PROCEDURE SP_TRAKSYS_GET_APP_SETTINGS()
RETURNS TABLE (SETTING_KEY VARCHAR, SETTING_VALUE STRING, SETTING_BLOB BYTES, HAS_BLOB BOOLEAN, CREATED_BY VARCHAR, UPDATED_BY VARCHAR)
LANGUAGE SQL
AS
$$
DECLARE
    res RESULTSET DEFAULT (
        SELECT SETTING_KEY, SETTING_VALUE, SETTING_BLOB, (SETTING_BLOB IS NOT NULL) AS HAS_BLOB, CREATED_BY, UPDATED_BY
        FROM REF_TRAKSYS_SETTINGS
    );
BEGIN
    RETURN TABLE(res);
END;
$$;

-- 4. Stored Procedure: Save App Setting
CREATE OR REPLACE PROCEDURE SP_TRAKSYS_SAVE_APP_SETTING(P_KEY VARCHAR, P_VAL STRING, P_USER VARCHAR)
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN
    MERGE INTO REF_TRAKSYS_SETTINGS t
    USING (SELECT :P_KEY AS k, :P_VAL AS v, COALESCE(:P_USER, CURRENT_USER()) AS u) s
    ON t.SETTING_KEY = s.k
    WHEN MATCHED THEN UPDATE SET SETTING_VALUE = s.v, UPDATED_BY = s.u, UPDATED_AT = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT (SETTING_KEY, SETTING_VALUE, CREATED_BY, UPDATED_BY, UPDATED_AT) VALUES (s.k, s.v, s.u, s.u, CURRENT_TIMESTAMP());
    RETURN 'SUCCESS';
END;
$$;

-- 5. Stored Procedure: Save App Setting Blob (for Logo Image Bytes)
CREATE OR REPLACE PROCEDURE SP_TRAKSYS_SAVE_APP_SETTING_BLOB(P_KEY VARCHAR, P_BLOB BYTES, P_USER VARCHAR)
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN
    MERGE INTO REF_TRAKSYS_SETTINGS t
    USING (SELECT :P_KEY AS k, :P_BLOB AS b, COALESCE(:P_USER, CURRENT_USER()) AS u) s
    ON t.SETTING_KEY = s.k
    WHEN MATCHED THEN UPDATE SET SETTING_BLOB = s.b, UPDATED_BY = s.u, UPDATED_AT = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT (SETTING_KEY, SETTING_BLOB, CREATED_BY, UPDATED_BY, UPDATED_AT) VALUES (s.k, s.b, s.u, s.u, CURRENT_TIMESTAMP());
    RETURN 'SUCCESS';
END;
$$;

-- 6. Stored Procedure: Get Suggested Questions
CREATE OR REPLACE PROCEDURE SP_TRAKSYS_GET_QUESTIONS()
RETURNS TABLE (QUESTION_ID INT, QUESTION_TEXT VARCHAR, DISPLAY_ORDER INT, CREATED_BY VARCHAR, UPDATED_BY VARCHAR)
LANGUAGE SQL
AS
$$
DECLARE
    res RESULTSET DEFAULT (
        SELECT QUESTION_ID, QUESTION_TEXT, DISPLAY_ORDER, CREATED_BY, UPDATED_BY
        FROM REF_TRAKSYS_QUESTIONS
        WHERE IS_ACTIVE = TRUE
        ORDER BY DISPLAY_ORDER ASC, QUESTION_ID ASC
    );
BEGIN
    RETURN TABLE(res);
END;
$$;

-- 7. Stored Procedure: Save Suggested Question (Add / Edit)
CREATE OR REPLACE PROCEDURE SP_TRAKSYS_SAVE_QUESTION(P_ID INT, P_TEXT VARCHAR, P_ORDER INT, P_USER VARCHAR)
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN
    IF (P_ID IS NULL OR P_ID <= 0) THEN
        INSERT INTO REF_TRAKSYS_QUESTIONS (QUESTION_TEXT, DISPLAY_ORDER, CREATED_BY, UPDATED_BY)
        VALUES (:P_TEXT, COALESCE(:P_ORDER, 1), COALESCE(:P_USER, CURRENT_USER()), COALESCE(:P_USER, CURRENT_USER()));
    ELSE
        UPDATE REF_TRAKSYS_QUESTIONS
        SET QUESTION_TEXT = :P_TEXT,
            DISPLAY_ORDER = COALESCE(:P_ORDER, DISPLAY_ORDER),
            UPDATED_BY = COALESCE(:P_USER, CURRENT_USER()),
            UPDATED_AT = CURRENT_TIMESTAMP()
        WHERE QUESTION_ID = :P_ID;
    END IF;
    RETURN 'SUCCESS';
END;
$$;

-- 8. Stored Procedure: Delete Suggested Question
CREATE OR REPLACE PROCEDURE SP_TRAKSYS_DELETE_QUESTION(P_ID INT, P_USER VARCHAR)
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN
    UPDATE REF_TRAKSYS_QUESTIONS
    SET IS_ACTIVE = FALSE,
        UPDATED_BY = COALESCE(:P_USER, CURRENT_USER()),
        UPDATED_AT = CURRENT_TIMESTAMP()
    WHERE QUESTION_ID = :P_ID;
    RETURN 'SUCCESS';
END;
$$;
