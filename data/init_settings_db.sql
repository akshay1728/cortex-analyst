-- 2. Application Settings Table
CREATE TABLE IF NOT EXISTS APP_SETTINGS (
    SETTING_KEY VARCHAR(100) PRIMARY KEY,
    SETTING_VALUE STRING,
    SETTING_BLOB BYTES,
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- 3. Stored Procedure: Get App Settings
CREATE OR REPLACE PROCEDURE PROC_GET_APP_SETTINGS()
RETURNS TABLE (SETTING_KEY VARCHAR, SETTING_VALUE STRING, HAS_BLOB BOOLEAN)
LANGUAGE SQL
AS
$$
DECLARE
    res RESULTSET DEFAULT (
        SELECT SETTING_KEY, SETTING_VALUE, (SETTING_BLOB IS NOT NULL) AS HAS_BLOB
        FROM APP_SETTINGS
    );
BEGIN
    RETURN TABLE(res);
END;
$$;

-- 4. Stored Procedure: Save App Setting
CREATE OR REPLACE PROCEDURE PROC_SAVE_APP_SETTING(P_KEY VARCHAR, P_VAL STRING)
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN
    MERGE INTO APP_SETTINGS t
    USING (SELECT :P_KEY AS k, :P_VAL AS v) s
    ON t.SETTING_KEY = s.k
    WHEN MATCHED THEN UPDATE SET SETTING_VALUE = s.v, UPDATED_AT = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT (SETTING_KEY, SETTING_VALUE, UPDATED_AT) VALUES (s.k, s.v, CURRENT_TIMESTAMP());
    RETURN 'SUCCESS';
END;
$$;

-- 5. Stored Procedure: Save App Setting Blob (for Logo Image Bytes)
CREATE OR REPLACE PROCEDURE PROC_SAVE_APP_SETTING_BLOB(P_KEY VARCHAR, P_BLOB BYTES)
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN
    MERGE INTO APP_SETTINGS t
    USING (SELECT :P_KEY AS k, :P_BLOB AS b) s
    ON t.SETTING_KEY = s.k
    WHEN MATCHED THEN UPDATE SET SETTING_BLOB = s.b, UPDATED_AT = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT (SETTING_KEY, SETTING_BLOB, UPDATED_AT) VALUES (s.k, s.b, CURRENT_TIMESTAMP());
    RETURN 'SUCCESS';
END;
$$;

-- 6. Stored Procedure: Get Suggested Questions
CREATE OR REPLACE PROCEDURE PROC_GET_SUGGESTED_QUESTIONS()
RETURNS TABLE (QUESTION_ID INT, QUESTION_TEXT VARCHAR, DISPLAY_ORDER INT)
LANGUAGE SQL
AS
$$
DECLARE
    res RESULTSET DEFAULT (
        SELECT QUESTION_ID, QUESTION_TEXT, DISPLAY_ORDER
        FROM APP_SUGGESTED_QUESTIONS
        WHERE IS_ACTIVE = TRUE
        ORDER BY DISPLAY_ORDER ASC, QUESTION_ID ASC
    );
BEGIN
    RETURN TABLE(res);
END;
$$;

-- 7. Stored Procedure: Save Suggested Question (Add / Edit)
CREATE OR REPLACE PROCEDURE PROC_SAVE_SUGGESTED_QUESTION(P_ID INT, P_TEXT VARCHAR, P_ORDER INT)
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN
    IF (P_ID IS NULL OR P_ID <= 0) THEN
        INSERT INTO APP_SUGGESTED_QUESTIONS (QUESTION_TEXT, DISPLAY_ORDER)
        VALUES (:P_TEXT, COALESCE(:P_ORDER, 1));
    ELSE
        UPDATE APP_SUGGESTED_QUESTIONS
        SET QUESTION_TEXT = :P_TEXT,
            DISPLAY_ORDER = COALESCE(:P_ORDER, DISPLAY_ORDER),
            UPDATED_AT = CURRENT_TIMESTAMP()
        WHERE QUESTION_ID = :P_ID;
    END IF;
    RETURN 'SUCCESS';
END;
$$;

-- 8. Stored Procedure: Delete Suggested Question
CREATE OR REPLACE PROCEDURE PROC_DELETE_SUGGESTED_QUESTION(P_ID INT)
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN
    UPDATE APP_SUGGESTED_QUESTIONS
    SET IS_ACTIVE = FALSE, UPDATED_AT = CURRENT_TIMESTAMP()
    WHERE QUESTION_ID = :P_ID;
    RETURN 'SUCCESS';
END;
$$;
